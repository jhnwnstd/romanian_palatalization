"""Morph-it! 0.4.8 as an automated check of Italian plurals (R11, R12).

Morph-it! (Zanchetta & Baroni 2005; CC BY-SA 2.0 / LGPL) is a full-form
lexicon, one ``form<TAB>lemma<TAB>tag`` line per analysis, built from
the la Repubblica corpus. Its two halves differ in evidential value:

  - **noun** lines (``NOUN-M:s``, ``NOUN-M:p``, ``NOUN-F:s``,
    ``NOUN-F:p``) were mostly entered after looking for corpus evidence
    of both numbers, so they can confirm a Wiktionary plural and give
    the noun's gender (feminine nouns are lemmatised on the feminine:
    amiche → amica);
  - **adjective** lines (``ADJ:pos+m+p`` …) are generated by rule for
    every adjective (porchi, cieci), so agreement with them is QC,
    never confirmation (R11). They are loaded for reporting only.

Forms and lemmas are compared through
:func:`lexpipe.langs.italian.keys.match_key`. The file is small (19 MB)
and read whole by the ``qc`` stage; its SHA-256 is pinned in
:mod:`lexpipe.sources` and recorded in the stage manifest.
"""

from __future__ import annotations

import re
from collections import defaultdict
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from lexpipe.langs.italian import keys

_NOUN_TAG_RE: Final[re.Pattern[str]] = re.compile(r"NOUN-([MF]):([sp])")
_ADJ_TAG_RE: Final[re.Pattern[str]] = re.compile(r"ADJ:pos\+([mf])\+([sp])")
GENDER_CODES: Final[Mapping[str, str]] = {"M": "m", "F": "f"}


@dataclass(frozen=True, slots=True)
class MorphIt:
    """Morph-it! nouns and adjectives keyed by lemma match key.

    ``noun_forms[(lemma, gender, number)]`` and
    ``adj_forms[(lemma, gender, number)]`` hold the forms (as written,
    distinct, sorted: Morph-it!'s line order carries no meaning, R5);
    gender is ``m``/``f``, number ``s``/``p``.
    """

    noun_forms: Mapping[tuple[str, str, str], tuple[str, ...]]
    adj_forms: Mapping[tuple[str, str, str], tuple[str, ...]]

    def noun_plurals(self, lemma: str, gender: str) -> tuple[str, ...]:
        return self.noun_forms.get((keys.match_key(lemma), gender, "p"), ())

    def noun_genders(self, lemma: str) -> tuple[str, ...]:
        """Genders under which *lemma* is a Morph-it! noun (sorted)."""
        key = keys.match_key(lemma)
        return tuple(
            gender
            for gender in ("f", "m")
            if (key, gender, "s") in self.noun_forms
            or (key, gender, "p") in self.noun_forms
        )

    def adj_plurals(self, lemma: str, gender: str) -> tuple[str, ...]:
        return self.adj_forms.get((keys.match_key(lemma), gender, "p"), ())


def _add(
    table: dict[tuple[str, str, str], dict[str, None]],
    key: tuple[str, str, str],
    form: str,
) -> None:
    table[key].setdefault(form, None)


def load(path: Path) -> MorphIt:
    """Read the Morph-it! file (UTF-8 mirror) into a :class:`MorphIt`."""
    nouns: dict[tuple[str, str, str], dict[str, None]] = defaultdict(dict)
    adjectives: dict[tuple[str, str, str], dict[str, None]] = defaultdict(dict)
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 3:
                continue
            form, lemma, tag = parts
            if (match := _NOUN_TAG_RE.fullmatch(tag)) is not None:
                gender = GENDER_CODES[match.group(1)]
                key = (keys.match_key(lemma), gender, match.group(2))
                _add(nouns, key, form)
            elif (match := _ADJ_TAG_RE.fullmatch(tag)) is not None:
                key = (keys.match_key(lemma), match.group(1), match.group(2))
                _add(adjectives, key, form)
    return MorphIt(
        noun_forms={k: tuple(sorted(v)) for k, v in nouns.items()},
        adj_forms={k: tuple(sorted(v)) for k, v in adjectives.items()},
    )
