@dataclass(frozen=True, slots=True)
class CellForms:
    """The Wiktionary forms of one lexeme cell."""

    forms: tuple[str, ...]
    provenance: tuple[str, ...]
    labelled: tuple[str, ...]


def read_plural_cells(
    path: Path,
) -> dict[str, dict[str, CellForms]]:
    """``{lexeme_id: {cell: CellForms}}`` from the plural forms table
    (rows without a form skipped; order kept)."""
    gathered: dict[str, dict[str, list[dict[str, str]]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for row in csvio.read_rows(path):
        if row["form"]:
            gathered[row["lexeme_id"]][row["cell"]].append(row)
    out: dict[str, dict[str, CellForms]] = {}
    for lexeme_id, cells in gathered.items():
        out[lexeme_id] = {}
        for cell, rows in cells.items():
            forms = tuple(dict.fromkeys(r["form"] for r in rows))
            provenance = tuple(dict.fromkeys(r["provenance"] for r in rows))
            labelled = tuple(
                dict.fromkeys(r["form"] for r in rows if r["labels"])
            )
            out[lexeme_id][cell] = CellForms(forms, provenance, labelled)
    return out


def _it_cells(row: Mapping[str, str]) -> dict[str, list[str]]:
    cells: dict[str, list[str]] = defaultdict(list)
    for item in csvio.split_list(row["it_forms"]):
        cell, _, form = item.partition(":")
        if form:
            cells[cell].append(form)
    return cells


def it_forms_for(row: Mapping[str, str], cell: str) -> list[str]:
    """it.wiktionary forms that speak to one Wiktionary cell."""
    cells = _it_cells(row)
    gender = row["gender"]
    if row["pos"] == "noun":
        if cell == heads.CELL_PL:
            extra = {"m": [heads.CELL_MPL], "f": [heads.CELL_FPL]}.get(
                gender, [heads.CELL_MPL, heads.CELL_FPL]
            )
            wanted = [heads.CELL_PL, *extra]
        else:
            wanted = [cell, heads.CELL_PL]
    elif cell == heads.CELL_PL:
        wanted = list(heads.CELLS)
    else:
        wanted = [cell]
    return list(dict.fromkeys(f for c in wanted for f in cells.get(c, [])))


def _feminine_lemmas(row: Mapping[str, str]) -> list[str]:
    stated = csvio.split_list(row["feminine_forms"])
    if stated:
        return stated
    word = row["word"]
    if row["pos"] == "adj" and word.endswith("o"):
        try:
            return [itcommon.make_feminine(word)]
        except itcommon.NotPortedError:
            return []
    return []


def morphit_forms_for(
    lexicon: morphit.MorphIt, row: Mapping[str, str], cell: str
) -> list[str]:
    """Morph-it! noun forms that speak to one Wiktionary cell."""
    word = row["word"]
    gender = row["gender"]
    found: list[str] = []
    if cell == heads.CELL_FPL:
        lemmas = _feminine_lemmas(row) or [word]
        for lemma in lemmas:
            found.extend(lexicon.noun_plurals(lemma, "f"))
        if row["pos"] == "noun" and gender in ("mf", "mfbysense"):
            found.extend(lexicon.noun_plurals(word, "f"))
    elif cell == heads.CELL_MPL:
        found.extend(lexicon.noun_plurals(word, "m"))
    elif row["pos"] == "noun" and gender in ("m", "f"):
        found.extend(lexicon.noun_plurals(word, gender))
    else:
        found.extend(lexicon.noun_plurals(word, "m"))
        found.extend(lexicon.noun_plurals(word, "f"))
    return list(dict.fromkeys(found))


def invariable_adjective(row: Mapping[str, str], cell: CellForms) -> bool:
    """An adjective whose only plural is its lemma (``inv``, ``#``).

    Morph-it! noun lines then belong to a homographic noun (tipo the
    noun has tipi; tipo the invariable adjective has none) and are not
    evidence about the adjective.
    """
    return row["pos"] == "adj" and cell.forms == (row["word"],)


def morphit_adj_forms_for(
    lexicon: morphit.MorphIt, row: Mapping[str, str], cell: str
) -> list[str]:
    """Generated Morph-it! adjective forms (reported, never counted)."""
    if row["pos"] != "adj":
        return []
    word = row["word"]
    genders = {heads.CELL_MPL: ("m",), heads.CELL_FPL: ("f",)}.get(
        cell, ("m", "f")
    )
    found = [f for g in genders for f in lexicon.adj_plurals(word, g)]
    return list(dict.fromkeys(found))


def _keys_of(forms: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(keys.match_key(form) for form in forms))


def variant_kind(
    word: str, forms: Sequence[str], labelled: Sequence[str]
) -> str:
    """velar_palatal | labelled | other (see the module docstring)."""
    key = keys.match_key(word)
    stem = morphology.analyze_lemma(key)
    outcomes = {
        morphology.analyze_form(key, stem, keys.match_key(form)).mutation
        for form in forms
    }
    if stem.dorsal and not stem.nde_class and {True, False} <= outcomes:
        return VELAR_PALATAL
    unlabelled = [form for form in forms if form not in labelled]
    if len(unlabelled) <= 1 and len(forms) > 1:
        return "labelled"
    return "other"


def classify_cell(
    word: str,
    cell: CellForms,
    morphit_forms: Sequence[str],
    it_forms: Sequence[str],
) -> tuple[str, str, str]:
    """``(plural_qc, qc_basis, variant_kind)`` of one cell."""
    wikt = _keys_of(cell.forms)
    from_morphit = set(_keys_of(morphit_forms))
    from_it = set(_keys_of(it_forms))
    independent = from_morphit | from_it
    agree = set(wikt) & independent
    extra = independent - set(wikt)
    sources = [
        name
        for name, found in (
            (SOURCE_MORPHIT, from_morphit),
            (SOURCE_IT, from_it),
        )
        if found
    ]
    if independent and not agree:
        return CONFLICT, "+".join(sources), ""
    if len(wikt) > 1 or extra:
        all_forms = [*cell.forms, *sorted(f for f in extra)]
        kind = variant_kind(word, all_forms, cell.labelled)
        return VARIANT, "+".join(sources), kind
    if agree:
        basis = "+".join(
            name
            for name, found in (
                (SOURCE_MORPHIT, from_morphit),
                (SOURCE_IT, from_it),
            )
            if found & agree
        )
        return CONFIRMED, basis, ""
    if cell.provenance == (plurals.MODULE_DEFAULT,):
        return MODULE_DEFAULT_ONLY, "module_default", ""
    return CONFIRMED, "explicit_only", ""


def gender_qc(
    row: Mapping[str, str], lexicon: morphit.MorphIt
) -> tuple[str, str]:
    """``(gender_qc, Morph-it! genders)`` of a noun ("" for others)."""
    if row["pos"] != "noun":
        return "", ""
    wikt = {
        "m": {"m"},
        "f": {"f"},
        "mf": {"m", "f"},
        "mfbysense": {"m", "f"},
    }.get(row["gender"], set())
    from_morphit = set(lexicon.noun_genders(row["word"]))
    from_it = set(csvio.split_list(row["it_gender"]))
    independent = [found for found in (from_morphit, from_it) if found]
    if not wikt or not independent:
        return "no_evidence", "|".join(sorted(from_morphit))
    if any(not (found & wikt) for found in independent):
        return CONFLICT, "|".join(sorted(from_morphit))
    return "agree", "|".join(sorted(from_morphit))


def qc_rows(
    lexicon_rows: Sequence[Mapping[str, str]],
    cells: Mapping[str, Mapping[str, CellForms]],
    lexicon: morphit.MorphIt,
) -> list[dict[str, Any]]:
    """Every QC row, sorted by lexeme_id and cell."""
    out: list[dict[str, Any]] = []
    order = {cell: index for index, cell in enumerate(heads.CELLS)}
    for row in lexicon_rows:
        lexeme_cells = cells.get(row["lexeme_id"], {})
        if not lexeme_cells:
            continue
        genders, morphit_genders = gender_qc(row, lexicon)
        dorsal = morphology.analyze_lemma(keys.match_key(row["word"])).dorsal
        for cell in sorted(lexeme_cells, key=order.__getitem__):
            forms = lexeme_cells[cell]
            suspect = suspect_forms(row["word"], forms.forms)
            found_morphit = (
                []
                if invariable_adjective(row, forms)
                else morphit_forms_for(lexicon, row, cell)
            )
            found_it = it_forms_for(row, cell)
            qc, basis, kind = classify_cell(
                row["word"], forms, found_morphit, found_it
            )
            source = [SOURCE_EN]
            if found_morphit:
                source.append(SOURCE_MORPHIT)
            if found_it:
                source.append(SOURCE_IT)
            out.append(
                {
                    "lexeme_id": row["lexeme_id"],
                    "word": row["word"],
                    "pos": row["pos"],
                    "gender": row["gender"],
                    "cell": cell,
                    "wiktionary_forms": list(forms.forms),
                    "provenance": list(forms.provenance),
                    "labelled_forms": list(forms.labelled),
                    "morphit_forms": found_morphit,
                    "morphit_adj_forms": morphit_adj_forms_for(
                        lexicon, row, cell
                    ),
                    "it_forms": found_it,
                    "plural_qc": qc,
                    "qc_basis": basis,
                    "variant_kind": kind,
                    "gender_qc": genders,
                    "morphit_genders": morphit_genders,
                    "it_gender": row["it_gender"],
                    "dorsal": dorsal,
                    "suspect": SUSPECT_E_PALATAL if suspect else "",
                    "suspect_forms": suspect,
                    "source": source,
                }
            )
    out.sort(key=lambda r: (r["lexeme_id"], order[r["cell"]]))
    return out


def suspect_forms(word: str, forms: Sequence[str]) -> list[str]:
    """Forms of a dorsal stem that palatalize before the plural -e
    (amica → *amice). Italian never does this (the Height effect), so
    such a form is most likely an editing error."""
    key = keys.match_key(word)
    stem = morphology.analyze_lemma(key)
    if not stem.dorsal or stem.nde_class:
        return []
    out: list[str] = []
    for form in forms:
        analysis = morphology.analyze_form(key, stem, keys.match_key(form))
        if analysis.opportunity == "e" and analysis.mutation is True:
            out.append(form)
    return out


