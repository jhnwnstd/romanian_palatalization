def frequency_ranks(
    lexicon_rows: Sequence[Mapping[str, str]], table: AttestationTable
) -> dict[str, int]:
    """Rank (1 = most frequent) of every attested in-domain lexeme by
    the folded count of its lemma form; ties by lexeme_id."""
    counted = [
        (table.count(keys.case_key(row["word"])), row["lexeme_id"])
        for row in lexicon_rows
        if row["domain"] == "in_domain"
    ]
    ordered = sorted(
        ((count, ident) for count, ident in counted if count > 0),
        key=lambda item: (-item[0], item[1]),
    )
    return {ident: rank for rank, (_, ident) in enumerate(ordered, 1)}


def _priority(qc_row: Mapping[str, Any]) -> int | None:
    qc = qc_row["plural_qc"]
    dorsal = qc_row["dorsal"]
    if qc == CONFLICT:
        return 1 if dorsal else 4
    if qc == VARIANT and qc_row["variant_kind"] == VELAR_PALATAL:
        return 2
    if qc_row["suspect"] == SUSPECT_E_PALATAL:
        return PRIORITY_SUSPECT
    if qc == MODULE_DEFAULT_ONLY and dorsal:
        return PRIORITY_DEFAULT_ONLY
    return None


PRIORITY_DEFAULT_ONLY: Final[int] = 3
PRIORITY_SUSPECT: Final[int] = 5
_ISSUES: Final[Mapping[int, str]] = {
    1: "independent sources give other plurals (dorsal stem)",
    2: "palatalized and velar plurals compete",
    3: "plural only generated by Module:it-common (dorsal stem)",
    4: "independent sources give other plurals",
    5: "palatalized plural in -e (-ce/-ge), unknown in Italian: "
    "probably an editing error",
}


def _url(template: str, word: str) -> str:
    return template.format(urllib.parse.quote(word, safe=""))


def worklist_rows(
    lexicon_rows: Sequence[Mapping[str, str]],
    rows: Sequence[Mapping[str, Any]],
    ranks: Mapping[str, int],
) -> list[dict[str, Any]]:
    """Flagged in-domain cells ordered by frequency rank."""
    in_domain = {
        r["lexeme_id"] for r in lexicon_rows if r["domain"] == "in_domain"
    }
    out: list[dict[str, Any]] = []
    for row in rows:
        priority = _priority(row)
        if priority is None or row["lexeme_id"] not in in_domain:
            continue
        if priority == PRIORITY_DEFAULT_ONLY and row["lexeme_id"] not in ranks:
            continue
        sources = [SOURCE_EN]
        if row["morphit_forms"]:
            sources.append(SOURCE_MORPHIT)
        if row["it_forms"]:
            sources.append(SOURCE_IT)
        out.append(
            {
                "freq_rank": ranks.get(row["lexeme_id"]),
                "priority": priority,
                "lexeme_id": row["lexeme_id"],
                "word": row["word"],
                "pos": row["pos"],
                "gender": row["gender"],
                "cell": row["cell"],
                "plural_qc": row["plural_qc"],
                "variant_kind": row["variant_kind"],
                "wiktionary_forms": row["wiktionary_forms"],
                "provenance": row["provenance"],
                "morphit_forms": row["morphit_forms"],
                "it_forms": row["it_forms"],
                "issue": _ISSUES[priority],
                "treccani_url": _url(TRECCANI_URL, row["word"]),
                "demauro_url": _url(DEMAURO_URL, row["word"]),
                "source": sources,
            }
        )
    unranked = 1 << 30
    out.sort(
        key=lambda r: (
            r["freq_rank"] if r["freq_rank"] is not None else unranked,
            r["priority"],
            r["lexeme_id"],
            r["cell"],
        )
    )
    return out


