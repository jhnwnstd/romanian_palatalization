def _table(title: str, counts: Mapping[str, int], total: int) -> list[str]:
    lines = [title]
    for key in sorted(counts):
        share = f"{100 * counts[key] / total:5.1f}%" if total else ""
        lines.append(f"  {key:<40} {counts[key]:>8,}  {share}")
    return lines + [""]


def _example(row: Mapping[str, Any]) -> str:
    def joined(items: Sequence[str]) -> str:
        return ", ".join(items) if items else "-"

    return (
        f"  {row['word']} ({row['pos']}, {row['cell']}): Wiktionary "
        f"{joined(row['wiktionary_forms'])} [{joined(row['provenance'])}];"
        f" Morph-it! {joined(row['morphit_forms'])};"
        f" it.wiktionary {joined(row['it_forms'])}"
    )


def report(
    lexicon_rows: Sequence[Mapping[str, str]],
    rows: Sequence[Mapping[str, Any]],
    ranks: Mapping[str, int],
    worklist: Sequence[Mapping[str, Any]],
    stamps: Mapping[str, str],
    summary: Mapping[str, str],
) -> str:
    """The text of ``italian_qc_report.txt`` (aggregates only)."""
    lines = [
        "Italian plural QC (tier 1: Morph-it! + it.wiktionary)",
        "=" * 54,
        "",
        "Inputs (SHA-256):",
        *[f"  {name}: {stamps[name]}" for name in sorted(stamps)],
        f"  Module:it-common port: revision {itcommon.MODULE_REVISION} "
        f"({itcommon.MODULE_TIMESTAMP})",
        "",
    ]
    drift = {
        k[len("drift:") :]: int(v)
        for k, v in summary.items()
        if k.startswith("drift:")
    }
    lines += _table("Drift test (lexicon stage; scope:status):", drift, 0)
    provenance = Counter(r["plural_provenance"] for r in lexicon_rows)
    lines += _table(
        "Plural provenance per lexeme (R12):", provenance, len(lexicon_rows)
    )
    qc_all = Counter(r["plural_qc"] for r in rows)
    lines += _table("plural_qc, all cells:", qc_all, len(rows))
    by_cell = Counter(
        f"{r['pos']} {r['cell']}: {r['plural_qc']}" for r in rows
    )
    lines += _table("plural_qc by part of speech and cell:", by_cell, 0)
    dorsal = [r for r in rows if r["dorsal"]]
    lines += _table(
        "plural_qc, dorsal stems (-co/-go/-ca/-ga…):",
        Counter(r["plural_qc"] for r in dorsal),
        len(dorsal),
    )
    lines += _table(
        "qc_basis:", Counter(r["qc_basis"] or "-" for r in rows), len(rows)
    )
    lines += _table(
        "variant_kind (variant cells):",
        Counter(r["variant_kind"] for r in rows if r["plural_qc"] == VARIANT),
        0,
    )
    nouns = {r["lexeme_id"]: r for r in rows if r["pos"] == "noun"}
    lines += _table(
        "gender_qc (nouns with a plural):",
        Counter(r["gender_qc"] for r in nouns.values()),
        len(nouns),
    )
    lines += _table(
        "Suspect plurals (dorsal stem palatalized before -e):",
        Counter(r["pos"] + " " + r["cell"] for r in rows if r["suspect"]),
        0,
    )
    lines += _table(
        "Manual worklist (tier 2) by priority:",
        Counter(f"{r['priority']} {r['issue']}" for r in worklist),
        len(worklist),
    )
    unranked = 1 << 30

    def by_rank(
        selected: Iterable[Mapping[str, Any]],
    ) -> list[Mapping[str, Any]]:
        return sorted(
            selected,
            key=lambda r: (
                ranks.get(r["lexeme_id"], unranked),
                r["lexeme_id"],
            ),
        )

    conflicts = by_rank(r for r in dorsal if r["plural_qc"] == CONFLICT)
    lines.append(
        f"Conflicts on dorsal stems, most frequent first "
        f"(first {EXAMPLES} of {len(conflicts)}):"
    )
    lines += [_example(r) for r in conflicts[:EXAMPLES]] + [""]
    variants = by_rank(r for r in rows if r["variant_kind"] == VELAR_PALATAL)
    lines.append(
        f"Velar/palatal variants, most frequent first "
        f"(first {EXAMPLES} of {len(variants)}):"
    )
    lines += [_example(r) for r in variants[:EXAMPLES]] + [""]
    lines += [
        "Notes:",
        "  - Morph-it! adjective lines are generated and are never counted",
        "    as confirmation (R11); only its noun lines are.",
        "  - 'confirmed' with qc_basis explicit_only: an editor typed the",
        "    plural and no independent source has the word.",
        "  - Examples are ordered by the lemma's frequency rank in",
        "    ita_news_2024_1M; counts are not reported (R9).",
    ]
    return "\n".join(lines) + "\n"


