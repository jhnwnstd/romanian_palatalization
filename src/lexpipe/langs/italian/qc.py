def _read_summary(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    with path.open("r", encoding="utf-8") as fh:
        next(fh, None)
        for line in fh:
            key, _, value = line.rstrip("\n").partition("\t")
            out[key] = value
    return out


def _body(ctx: RunContext, layout: Layout, words: Path) -> int:
    lexicon_rows = csvio.read_rows(layout.lexicon_full)
    cells = read_plural_cells(layout.plural_forms)
    lexicon = morphit.load(layout.morphit)
    rows = qc_rows(lexicon_rows, cells, lexicon)
    table = leipzig.attestation_table(ctx, words)
    ranks = frequency_ranks(lexicon_rows, table)
    worklist = worklist_rows(lexicon_rows, rows, ranks)
    csvio.write_rows(layout.qc, rows, QC_FIELDS, ctx=ctx)
    stamps = {
        "morphit": sha256_file(layout.morphit),
        "italian_lexicon_full.csv": sha256_file(layout.lexicon_full),
    }
    summary = _read_summary(layout.lexicon_summary)
    ctx.write_tracked_text(
        layout.qc_report,
        report(lexicon_rows, rows, ranks, worklist, stamps, summary),
        sources=REPORT_SOURCES,
    )
    csvio.write_tracked(layout.worklist, worklist, WORKLIST_FIELDS, ctx=ctx)
    counts = Counter(r["plural_qc"] for r in rows)
    print(
        f"  {len(rows):,} cells: "
        + ", ".join(f"{k} {counts[k]:,}" for k in PLURAL_QC)
        + f"; worklist {len(worklist):,} rows"
    )
    return 0


def outputs(layout: Layout) -> list[Path]:
    return [layout.qc, layout.qc_report, layout.worklist]


def run(ctx: RunContext) -> int | None:
    """Run the ``qc`` stage (skipped when its manifest matches)."""
    layout = Layout(ctx)
    words = leipzig.words_file(ctx, layout)
    return run_stage(
        ctx,
        STAGE,
        inputs=[
            layout.lexicon_full,
            layout.plural_forms,
            layout.lexicon_summary,
            layout.morphit,
            words,
        ],
        params={"version": VERSION},
        outputs=outputs(layout),
        body=lambda: _body(ctx, layout, words),
    )
