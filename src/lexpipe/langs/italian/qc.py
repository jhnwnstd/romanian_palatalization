"""Stage ``qc``: the Italian "DEX substitute" (design §3, R11, R12).

There is no open Italian dictionary with authoritative plurals, so
plurals are checked in two tiers:

  **Tier 1 (automated, this stage).** Every Wiktionary plural cell is
  compared with two sources independent of en.wiktionary's module
  defaults: Morph-it! noun lines (mostly corpus-attested; adjective
  lines are generated and never confirm anything, R11) and the
  it.wiktionary edition's hand-entered plurals.

  **Tier 2 (by hand, outside the pipeline).** Flagged lexemes go to a
  worklist with Treccani and De Mauro URLs for manual lookup; the
  pipeline never fetches either (Treccani opts out of text and data
  mining and plants trap URLs). Decisions are recorded as coded values
  plus a citation in ``curated/italian/plural_adjudications.csv``
  (keyed by lexeme_id with guard columns; loaded and guard-checked by
  the ``features`` stage).

plural_qc (per lexeme × cell; R12)
----------------------------------
With W the Wiktionary forms of the cell (match keys; labelled variants
included) and I the forms the independent sources give for it:

  conflict             I is not empty and shares no form with W
  variant              W has several forms, or I adds a form W lacks
                       (``variant_kind``: velar_palatal — a dorsal stem
                       with both outcomes, chirurghi ~ chirurgi —,
                       labelled — the other forms all carry usage
                       labels —, or other)
  confirmed            one form, attested by I (``qc_basis`` morphit,
                       wiktionary_it or both), or typed by an editor
                       with no independent evidence either way
                       (``qc_basis = explicit_only``)
  module_default_only  one form, generated by Module:it-common, and no
                       independent source attests it

Cells without a Wiktionary form (uncountable, plurale tantum) get no
row. ``suspect = e_palatal`` marks a dorsal stem whose Wiktionary plural
palatalizes before -e (fluidodinamica → *fluidodinamice*): Italian never
does (the Height effect), so the form is most likely an editing error.

The cell comparisons: nouns use Morph-it! ``NOUN-M:p``/``NOUN-F:p``
by gender (feminine counterparts under their own lemma); adjectives use
the noun lines of the same lemma when the word is also a noun, except
for an invariable adjective, whose homographic noun says nothing about
it (tipo).
``gender_qc`` (nouns) compares the Wiktionary gender with Morph-it! and
it.wiktionary: agree | conflict | no_evidence.

Outputs
-------
``data/italian/italian_qc.csv`` (gitignored): one row per lexeme ×
cell, sorted by lexeme_id and cell.

``analysis/italian/italian_qc_report.txt`` (tracked, aggregates and
examples only — Wiktionary and Morph-it! forms, no counts).

``analysis/italian/italian_manual_worklist.csv`` (tracked, through
:func:`lexpipe.csvio.write_tracked`): in-domain lexemes whose cell is a
conflict, a velar/palatal variant, a suspect -ce/-ge plural, or a
module default without independent evidence on a dorsal
(-co/-go/-ca/-ga) stem; ordered by
the lemma's frequency rank in the Leipzig corpus (rank only, never the
count, R9). Module defaults without evidence are listed only for lemmas
attested in the corpus (there are thousands of unattested ones). Each
row has Treccani (``https://www.treccani.it/vocabolario/<w>/``)
and De Mauro (``https://dizionario.internazionale.it/parola/<w>``)
URLs.
"""

