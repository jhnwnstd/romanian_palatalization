"""Per-form plural provenance of Italian lexemes (design rule R12).

Each noun or adjective lexeme's plurals are read from the arguments of
its ``{{it-noun}}``/``{{it-adj}}`` head (:mod:`.heads`), never from
kaikki's ``forms``. Every plural form becomes a :class:`PluralRow`:

    cell        pl | m.pl | f.pl (:data:`heads.CELLS`)
    form        the plural as written ("" for a row that states no form:
                the codes - ~ ? !, or a default the module cannot give)
    provenance  explicit (typed by an editor; ``#`` invariables
                included) | module_default (generated by
                Module:it-common: the code ``+``, ``++``, ``cap*``,
                ``cap*+``, or no plural argument at all)
    code        the item's code (:data:`heads.CODES`), "" for a typed
                form, ``default`` for an implicit default
    gender      the item's ``<g:>`` (uova<g:f>), else ""
    qualifiers  ``q:``/``qq:``/``l:``/``ll:`` modifiers, in order
    labels      normalised usage labels (archaic, literary, …), sorted
    raw_arg     ``key=item`` exactly as written ("" for implicit
                defaults; ``inv=1`` for invariable adjectives)
    tag_error   "" | unbalanced | bad_modifier (the item's brackets) |
                default_error (the module raises: gender-specific
                default for mf/mfbysense/?) | not_ported (multiword) |
                no_default (the module has no rule for the ending)
    item        position in source order within the lexeme

Resolution of codes (:func:`resolve_plurals`):

  - ``+``: the cell's module default: ``pl`` = make_plural(lemma,
    item gender or noun gender); ``m.pl`` = make_plural(lemma, "m");
    ``f.pl`` = make_plural(feminine, "f") for each feminine singular
    (the ``f`` argument; an adjective's default make_feminine(lemma);
    a noun's lemma);
  - ``#`` → the lemma (invariable); a form containing ``#`` → the
    lemma substituted (``#s`` → pesos);
  - ``++`` → every space/hyphen-separated part pluralised
    (divano-letto → divani-letti);
  - ``cap*``/``cap*+`` → Module:it-common's capo- specials;
  - ``-``, ``?``, ``!`` → a row without a form; ``~`` alone (countable
    and uncountable) also gets the default plural, as the module does
    (latte → latti).

Heads without plural arguments get the defaults of
:mod:`.itcommon` (``noun_default_cells`` / ``adjective_default_cells``);
an adjective with some cells stated keeps the default for the others
(carico: m.pl carichi explicit, f.pl cariche default). Plurale tantum
nouns (``m-p``/``f-p``) and ``noforms`` adjectives get no rows.

:func:`drift` compares the resolved forms with the plurals kaikki
rendered (R12 drift test; see :mod:`.lexicon`).
"""

from __future__ import annotations

import unicodedata
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any, Final

from lexpipe import kaikki
from lexpipe.langs.italian import heads, itcommon

EXPLICIT: Final[str] = "explicit"
MODULE_DEFAULT: Final[str] = "module_default"
IMPLICIT_CODE: Final[str] = "default"

ERROR_DEFAULT: Final[str] = "default_error"
ERROR_NOT_PORTED: Final[str] = "not_ported"
ERROR_NO_DEFAULT: Final[str] = "no_default"

# plural_status values (one per lexeme; see plural_status()).
STATUS_REGULAR: Final[str] = "regular"
STATUS_INVARIABLE: Final[str] = "invariable"
STATUS_UNCOUNTABLE: Final[str] = "uncountable"
STATUS_PLURALE_TANTUM: Final[str] = "plurale_tantum"
STATUS_UNKNOWN: Final[str] = "unknown"
STATUS_NOFORMS: Final[str] = "noforms"
STATUS_NO_HEAD: Final[str] = "no_head_template"
STATUS_NONE: Final[str] = "none"

COUNTABILITY: Final[Mapping[str, str]] = {
    "-": "uncountable",
    "~": "countable_and_uncountable",
    "?": "plural_unknown",
    "!": "plural_unattested",
}

DRIFT_SCOPES: Final[tuple[str, ...]] = (
    "pure_default_noun",
    "pure_default_adj",
    "with_arguments",
)
DRIFT_MATCH: Final[str] = "match"
DRIFT_MISMATCH: Final[str] = "mismatch"
DRIFT_PORT_ERROR: Final[str] = "port_error"
DRIFT_NOT_PORTED: Final[str] = "not_ported"


@dataclass(frozen=True, slots=True)
class PluralRow:
    """One plural form of a lexeme (see the module docstring)."""

    cell: str
    form: str
    provenance: str
    code: str
    gender: str
    qualifiers: tuple[str, ...]
    labels: tuple[str, ...]
    raw_arg: str
    tag_error: str
    item: int


@dataclass(frozen=True, slots=True)
class PluralInfo:
    """Everything the head says about a lexeme's plurals."""

    template: str
    rows: tuple[PluralRow, ...]
    genders: tuple[heads.GenderCode, ...] = ()
    feminines: tuple[str, ...] = ()
    masculines: tuple[str, ...] = ()
    pure_default: bool = False
    noforms: bool = False
    head_errors: tuple[str, ...] = field(default=())

    @property
    def forms(self) -> tuple[str, ...]:
        """Plural forms in row order (empty forms skipped)."""
        return tuple(row.form for row in self.rows if row.form)

    def cell_forms(self, cell: str) -> tuple[str, ...]:
        """Distinct forms of one cell, in row order."""
        seen: dict[str, None] = {}
        for row in self.rows:
            if row.cell == cell and row.form:
                seen.setdefault(row.form, None)
        return tuple(seen)

    @property
    def codes(self) -> tuple[str, ...]:
        """Distinct codes of the rows, in row order."""
        seen: dict[str, None] = {}
        for row in self.rows:
            if row.code:
                seen.setdefault(row.code, None)
        return tuple(seen)

    @property
    def plurale_tantum(self) -> bool:
        return any(code.plural_only for code in self.genders)

    @property
    def provenance(self) -> str:
        """explicit | module_default | mixed | none (rows with forms)."""
        kinds = {row.provenance for row in self.rows if row.form}
        if not kinds:
            return STATUS_NONE
        if len(kinds) > 1:
            return "mixed"
        return next(iter(kinds))

    @property
    def countability(self) -> str:
        """Countability codes of the head, "|"-joined in order."""
        found = [COUNTABILITY[c] for c in self.codes if c in COUNTABILITY]
        return "|".join(found)

    @property
    def status(self) -> str:
        """One-word summary (``plural_status``)."""
        if not self.template:
            return STATUS_NO_HEAD
        if self.plurale_tantum:
            return STATUS_PLURALE_TANTUM
        if self.noforms:
            return STATUS_NOFORMS
        forms = self.forms
        if not forms:
            codes = self.codes
            if "-" in codes:
                return STATUS_UNCOUNTABLE
            if "?" in codes or "!" in codes:
                return STATUS_UNKNOWN
            return STATUS_NONE
        return STATUS_REGULAR

    @property
    def invariable(self) -> bool:
        """Some plural row is the ``#`` code (plural = lemma)."""
        return any(row.code == "#" for row in self.rows)


def _nfc(text: str) -> str:
    return unicodedata.normalize("NFC", text)


def _substitute(text: str, lemma: str) -> str:
    return _nfc(text.replace(heads.LEMMA_PLACEHOLDER, lemma))


def _counterparts(value: str | None, lemma: str, make: Any) -> tuple[str, ...]:
    """Resolve an ``f``/``m`` argument (``+`` → *make*(lemma))."""
    if not value:
        return ()
    out: list[str] = []
    for item in heads.parse_list(value):
        if item.code == "+":
            try:
                out.append(make(lemma))
            except itcommon.NotPortedError:
                continue
        elif item.text and not item.code:
            out.append(_substitute(item.text, lemma))
        elif item.code == "#":
            out.append(lemma)
    return tuple(out)


@dataclass
class _Builder:
    """Accumulates rows for one lexeme."""

    lemma: str
    template: str
    gender: str
    feminines: tuple[str, ...]
    rows: list[PluralRow] = field(default_factory=list)

    def add(
        self,
        cell: str,
        form: str,
        provenance: str,
        code: str,
        *,
        item: heads.ArgItem | None = None,
        raw_arg: str = "",
        error: str = "",
    ) -> None:
        self.rows.append(
            PluralRow(
                cell=cell,
                form=form,
                provenance=provenance,
                code=code,
                gender=item.gender if item else "",
                qualifiers=item.qualifiers if item else (),
                labels=item.labels if item else (),
                raw_arg=raw_arg,
                tag_error=error or (item.error if item else ""),
                item=len(self.rows),
            )
        )

    # -- defaults ----------------------------------------------------------

    def default_forms(
        self, cell: str, gender: str = "", special: str | None = None
    ) -> list[str]:
        """Module defaults of *cell*; raises like make_plural."""
        if cell == heads.CELL_MPL:
            form = itcommon.make_plural(self.lemma, "m", special)
            return [form] if form else []
        if cell == heads.CELL_FPL:
            singulars = self.feminines or (self.lemma,)
            if special is not None:
                singulars = (self.lemma,)
            found = [itcommon.make_plural(f, "f", special) for f in singulars]
            return [form for form in found if form]
        noun_gender = gender or self.gender
        if self.template == heads.ADJ_TEMPLATE:
            noun_gender = "m"
        form = itcommon.make_plural(self.lemma, noun_gender, special)
        return [form] if form else []

    def add_defaults(
        self,
        cell: str,
        code: str,
        *,
        item: heads.ArgItem | None = None,
        raw_arg: str = "",
        special: str | None = None,
    ) -> None:
        gender = item.gender if item else ""
        try:
            forms = self.default_forms(cell, gender, special)
        except itcommon.DefaultPluralError:
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_DEFAULT,
            )
            return
        except itcommon.NotPortedError:
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_NOT_PORTED,
            )
            return
        if not forms:
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_NO_DEFAULT,
            )
        for form in forms:
            self.add(
                cell, form, MODULE_DEFAULT, code, item=item, raw_arg=raw_arg
            )

    def add_multipart(
        self, cell: str, item: heads.ArgItem, raw_arg: str
    ) -> None:
        gender = item.gender or self.gender
        parts: list[str] = []
        token = ""
        for ch in self.lemma:
            if ch in " -":
                parts.extend([token, ch])
                token = ""
            else:
                token += ch
        parts.append(token)
        try:
            out = [
                p if p in (" ", "-") else itcommon.make_plural(p, gender)
                for p in parts
            ]
        except (itcommon.DefaultPluralError, itcommon.NotPortedError):
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_DEFAULT,
            )
            return
        if any(piece is None for piece in out):
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_NO_DEFAULT,
            )
            return
        form = "".join(piece for piece in out if piece is not None)
        self.add(
            cell, form, MODULE_DEFAULT, item.code, item=item, raw_arg=raw_arg
        )

    # -- one argument item -------------------------------------------------

    def add_item(self, slot: heads.Slot, item: heads.ArgItem) -> None:
        raw_arg = f"{slot.key}={item.raw}"
        code = item.code
        if code in ("-", "~", "?", "!"):
            self.add(slot.cell, "", EXPLICIT, code, item=item, raw_arg=raw_arg)
        elif code == "#":
            self.add(
                slot.cell,
                self.lemma,
                EXPLICIT,
                code,
                item=item,
                raw_arg=raw_arg,
            )
        elif code == "+" and self.by_sense(slot, item):
            self.add_gendered(item, raw_arg, None)
        elif code == "+":
            self.add_defaults(slot.cell, code, item=item, raw_arg=raw_arg)
        elif code in itcommon.CAP_SPECIALS and self.by_sense(slot, item):
            self.add_gendered(item, raw_arg, code)
        elif heads.MULTIWORD_SPECIAL_RE.fullmatch(code):
            self.add(
                slot.cell,
                "",
                MODULE_DEFAULT,
                code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_NOT_PORTED,
            )
        elif code == "++":
            self.add_multipart(slot.cell, item, raw_arg)
        elif code in itcommon.CAP_SPECIALS:
            cell_gender = {heads.CELL_MPL: "m", heads.CELL_FPL: "f"}.get(
                slot.cell, self.gender
            )
            self.add_capo(slot.cell, item, raw_arg, cell_gender)
        elif item.text:
            self.add(
                slot.cell,
                _substitute(item.text, self.lemma),
                EXPLICIT,
                "",
                item=item,
                raw_arg=raw_arg,
            )
        else:
            self.add(
                slot.cell,
                "",
                EXPLICIT,
                "",
                item=item,
                raw_arg=raw_arg,
                error=item.error or heads.ERROR_BAD_MODIFIER,
            )

    def by_sense(self, slot: heads.Slot, item: heads.ArgItem) -> bool:
        """A ``pl`` item of an mf/mfbysense noun without ``<g:>``: the
        module derives a masculine and a feminine plural from it."""
        return (
            self.template == heads.NOUN_TEMPLATE
            and slot.cell == heads.CELL_PL
            and self.gender in ("mf", "mfbysense")
            and not item.gender
        )

    def add_gendered(
        self, item: heads.ArgItem, raw_arg: str, special: str | None
    ) -> None:
        """``+``/``cap*``/``cap*+`` of an mf noun: m.pl and f.pl, or one
        ``pl`` row when both are the same form (cantante → cantanti)."""
        try:
            masculine = itcommon.make_plural(self.lemma, "m", special)
            feminine = itcommon.make_plural(self.lemma, "f", special)
        except itcommon.DefaultPluralError:
            self.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_DEFAULT,
            )
            return
        except itcommon.NotPortedError:
            self.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_NOT_PORTED,
            )
            return
        if masculine == feminine:
            cells = [(heads.CELL_PL, masculine)]
        else:
            cells = [(heads.CELL_MPL, masculine), (heads.CELL_FPL, feminine)]
        for cell, form in cells:
            self.add(
                cell,
                form or "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error="" if form else ERROR_NO_DEFAULT,
            )

    def add_capo(
        self, cell: str, item: heads.ArgItem, raw_arg: str, gender: str
    ) -> None:
        try:
            form = itcommon.make_plural(self.lemma, gender, item.code)
        except (itcommon.DefaultPluralError, itcommon.NotPortedError):
            self.add(
                cell,
                "",
                MODULE_DEFAULT,
                item.code,
                item=item,
                raw_arg=raw_arg,
                error=ERROR_DEFAULT,
            )
            return
        self.add(
            cell,
            form or "",
            MODULE_DEFAULT,
            item.code,
            item=item,
            raw_arg=raw_arg,
            error="" if form else ERROR_NO_DEFAULT,
        )


def _noun_info(lemma: str, args: Mapping[str, str]) -> PluralInfo:
    genders = heads.parse_gender(args.get("1", ""))
    gender = genders[0].base if genders else ""
    masculines = _counterparts(args.get("m"), lemma, itcommon.make_masculine)
    feminines = _counterparts(args.get("f"), lemma, itcommon.make_feminine)
    builder = _Builder(lemma, heads.NOUN_TEMPLATE, gender, feminines)
    slots = heads.plural_slots(heads.NOUN_TEMPLATE, args)
    errors = tuple(code.error for code in genders if code.error)
    if any(code.plural_only for code in genders):
        return PluralInfo(
            heads.NOUN_TEMPLATE,
            (),
            genders,
            feminines,
            masculines,
            not slots,
            False,
            errors,
        )
    for slot in slots:
        for item in slot.items:
            builder.add_item(slot, item)
    _noun_completion(builder, slots, gender)
    return PluralInfo(
        heads.NOUN_TEMPLATE,
        tuple(builder.rows),
        genders,
        feminines,
        masculines,
        pure_default=not slots,
        head_errors=errors,
    )


def _noun_completion(
    builder: _Builder, slots: Sequence[heads.Slot], gender: str
) -> None:
    """Implicit defaults of a noun head (module docstring)."""
    stated = {slot.cell for slot in slots}
    if not slots:
        try:
            cells = itcommon.noun_default_cells(builder.lemma, gender)
        except itcommon.DefaultPluralError:
            builder.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                IMPLICIT_CODE,
                error=ERROR_DEFAULT,
            )
            return
        except itcommon.NotPortedError:
            builder.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                IMPLICIT_CODE,
                error=ERROR_NOT_PORTED,
            )
            return
        if not cells:
            builder.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                IMPLICIT_CODE,
                error=ERROR_NO_DEFAULT,
            )
        for cell, form in cells:
            builder.add(cell, form, MODULE_DEFAULT, IMPLICIT_CODE)
        return
    only_countability = [
        item.code
        for slot in slots
        if slot.cell == heads.CELL_PL
        for item in slot.items
    ] == ["~"]
    if only_countability:
        builder.add_defaults(heads.CELL_PL, IMPLICIT_CODE)
    if gender in ("mf", "mfbysense") and heads.CELL_PL not in stated:
        gendered = {heads.CELL_MPL, heads.CELL_FPL}
        if stated & gendered:
            for cell in sorted(gendered - stated):
                builder.add_defaults(cell, IMPLICIT_CODE)


def _adjective_info(lemma: str, args: Mapping[str, str]) -> PluralInfo:
    feminines = _counterparts(args.get("f"), lemma, itcommon.make_feminine)
    builder = _Builder(lemma, heads.ADJ_TEMPLATE, "m", feminines)
    if not feminines:
        try:
            builder.feminines = (itcommon.make_feminine(lemma),)
        except itcommon.NotPortedError:
            builder.feminines = ()
    if args.get("noforms"):
        return PluralInfo(
            heads.ADJ_TEMPLATE,
            (),
            (),
            feminines,
            (),
            pure_default=True,
            noforms=True,
        )
    if args.get("inv"):
        builder.add(
            heads.CELL_PL, lemma, EXPLICIT, "#", raw_arg=f"inv={args['inv']}"
        )
        return PluralInfo(
            heads.ADJ_TEMPLATE,
            tuple(builder.rows),
            (),
            feminines,
            (),
            pure_default=False,
        )
    slots = heads.plural_slots(heads.ADJ_TEMPLATE, args)
    for slot in slots:
        for item in slot.items:
            builder.add_item(slot, item)
    _adjective_completion(builder, slots, args, feminines)
    return PluralInfo(
        heads.ADJ_TEMPLATE,
        tuple(builder.rows),
        (),
        feminines,
        (),
        pure_default=not slots,
    )


def _adjective_completion(
    builder: _Builder,
    slots: Sequence[heads.Slot],
    args: Mapping[str, str],
    feminines: Sequence[str],
) -> None:
    stated = {slot.cell for slot in slots}
    try:
        cells = itcommon.adjective_default_cells(
            builder.lemma, feminines, feminine_only=bool(args.get("fonly"))
        )
    except itcommon.DefaultPluralError:
        if not slots:
            builder.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                IMPLICIT_CODE,
                error=ERROR_DEFAULT,
            )
        return
    except itcommon.NotPortedError:
        if not slots:
            builder.add(
                heads.CELL_PL,
                "",
                MODULE_DEFAULT,
                IMPLICIT_CODE,
                error=ERROR_NOT_PORTED,
            )
        return
    if heads.CELL_PL in stated:
        return
    for cell, form in cells:
        if cell not in stated:
            builder.add(cell, form, MODULE_DEFAULT, IMPLICIT_CODE)
    if not cells and not slots:
        builder.add(
            heads.CELL_PL,
            "",
            MODULE_DEFAULT,
            IMPLICIT_CODE,
            error=ERROR_NO_DEFAULT,
        )


def _one_head(lemma: str, name: str, args: Mapping[str, str]) -> PluralInfo:
    if name == heads.NOUN_TEMPLATE:
        return _noun_info(lemma, args)
    if name == heads.ADJ_TEMPLATE:
        return _adjective_info(lemma, args)
    return PluralInfo("", ())


def _merge(infos: Sequence[PluralInfo]) -> PluralInfo:
    """One :class:`PluralInfo` for an entry with several heads (e.g. a
    masculine and a feminine ``{{it-noun}}``): rows concatenated in
    head order, ``raw_arg`` prefixed with ``h<n>:`` from the second
    head on."""
    first = infos[0]
    rows: list[PluralRow] = []
    for number, info in enumerate(infos, 1):
        for row in info.rows:
            raw = row.raw_arg if number == 1 else f"h{number}:{row.raw_arg}"
            rows.append(
                PluralRow(
                    row.cell,
                    row.form,
                    row.provenance,
                    row.code,
                    row.gender,
                    row.qualifiers,
                    row.labels,
                    raw,
                    row.tag_error,
                    len(rows),
                )
            )
    return PluralInfo(
        first.template,
        tuple(rows),
        tuple(code for info in infos for code in info.genders),
        tuple(dict.fromkeys(f for info in infos for f in info.feminines)),
        tuple(dict.fromkeys(m for info in infos for m in info.masculines)),
        pure_default=all(info.pure_default for info in infos),
        noforms=any(info.noforms for info in infos),
        head_errors=tuple(e for info in infos for e in info.head_errors),
    )


def resolve_plurals(
    lemma: str, head_templates: Sequence[Mapping[str, Any]]
) -> PluralInfo:
    """:class:`PluralInfo` of a lexeme from its head templates.

    Every ``{{it-noun}}``/``{{it-adj}}`` head of the entry counts, in
    order; the first one names the template.
    """
    infos = [
        _one_head(lemma, str(t.get("name")), _string_args(t))
        for t in head_templates
        if isinstance(t, Mapping) and t.get("name") in heads.HEAD_TEMPLATES
    ]
    if not infos:
        return PluralInfo("", ())
    return infos[0] if len(infos) == 1 else _merge(infos)


def _string_args(template: Mapping[str, Any]) -> dict[str, str]:
    args = template.get("args")
    if not isinstance(args, Mapping):
        return {}
    return {str(k): str(v) for k, v in args.items()}


