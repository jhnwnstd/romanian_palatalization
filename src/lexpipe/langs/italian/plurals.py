# Drift: resolved plurals vs kaikki's rendered plurals
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Drift:
    """Comparison of the resolved plurals with kaikki's."""

    scope: str
    status: str
    resolved: tuple[str, ...]
    rendered: tuple[str, ...]


def rendered_cells(entry: Mapping[str, Any]) -> dict[str, tuple[str, ...]]:
    """kaikki's plural forms by cell (masculine → m.pl, feminine →
    f.pl, else pl), distinct and sorted per cell."""
    found: dict[str, set[str]] = {}
    for form in kaikki.plural_forms(entry):
        tags = set(form.tags)
        if "masculine" in tags and "feminine" not in tags:
            cell = heads.CELL_MPL
        elif "feminine" in tags and "masculine" not in tags:
            cell = heads.CELL_FPL
        else:
            cell = heads.CELL_PL
        found.setdefault(cell, set()).add(_nfc(form.form))
    return {cell: tuple(sorted(forms)) for cell, forms in found.items()}


def _flat(cells: Mapping[str, Sequence[str]]) -> tuple[str, ...]:
    return tuple(
        sorted(
            {
                f"{cell}:{form}"
                for cell, forms in cells.items()
                for form in forms
            }
        )
    )


_INVARIABLE_CODES: Final[frozenset[str]] = frozenset({"#", "cap*", "cap*+"})
RENDERING_ARTIFACTS: Final[frozenset[str]] = frozenset(
    {"invariable", "is feminine", "is masculine"}
)


def drift(info: PluralInfo, entry: Mapping[str, Any]) -> Drift | None:
    """Compare *info* with the plurals kaikki rendered for *entry*.

    Pure-default heads are compared cell by cell (the R12 drift test);
    heads with plural arguments by their sets of forms (a check of the
    argument parser). None for lexemes without plurals to compare
    (no head template, plurale tantum, ``noforms``).
    """
    if not info.template or info.plurale_tantum or info.noforms:
        return None
    if info.pure_default:
        scope = (
            "pure_default_noun"
            if info.template == heads.NOUN_TEMPLATE
            else "pure_default_adj"
        )
    else:
        scope = "with_arguments"
    errors = {row.tag_error for row in info.rows if row.tag_error}
    lemma = _nfc(str(entry.get("word") or ""))
    rendered = {
        cell: tuple(f for f in forms if f not in RENDERING_ARTIFACTS)
        for cell, forms in rendered_cells(entry).items()
    }
    rendered = {cell: forms for cell, forms in rendered.items() if forms}
    with_forms = [row for row in info.rows if row.form]
    invariable_only = bool(with_forms) and all(
        row.form == lemma and row.code in _INVARIABLE_CODES
        for row in with_forms
    )
    resolved: dict[str, set[str]] = {}
    for row in with_forms:
        if invariable_only or (
            row.form == lemma and row.code in itcommon.CAP_SPECIALS
        ):
            continue
        resolved.setdefault(row.cell, set()).add(row.form)
    if scope == "with_arguments":
        stated_invariable = "#" in info.codes
        left = tuple(
            sorted(
                {
                    row.form
                    for row in with_forms
                    if row.code != "#"
                    and row.cell in resolved
                    and row.form in resolved[row.cell]
                }
            )
        )
        right = tuple(
            sorted(
                {
                    f
                    for forms in rendered.values()
                    for f in forms
                    if not (stated_invariable and f == lemma)
                }
            )
        )
    else:
        left = _flat({c: sorted(f) for c, f in resolved.items()})
        right = _flat(rendered)
    if ERROR_NOT_PORTED in errors and not left:
        status = DRIFT_NOT_PORTED
    elif errors & {ERROR_DEFAULT, ERROR_NO_DEFAULT} and not left:
        status = DRIFT_PORT_ERROR if right else DRIFT_MATCH
    else:
        status = DRIFT_MATCH if left == right else DRIFT_MISMATCH
    return Drift(scope, status, left, right)
